var s=UnityEngine.SceneManagement.SceneManager.GetSceneByPath("Assets/Scenes/Main Game Scene.unity");
var m=s.GetRootGameObjects().SelectMany(g=>g.GetComponentsInChildren<CablewayMovementManager>(true)).Single();
if(EditorApplication.isPlaying || AnimationMode.InAnimationMode())throw new Exception("Idle edit mode required");
m.PrepareMovement();
var flags=System.Reflection.BindingFlags.NonPublic|System.Reflection.BindingFlags.Instance;
var offsets=(float[])typeof(CablewayMovementManager).GetField("startingDistances",flags).GetValue(m);
var at=typeof(CablewayMovementManager).GetMethod("PositionAtDistance",flags);
int index=Array.FindIndex(m.Buckets,t=>t.name=="CoalBucket (1)" && t.parent.name=="CablewayTower_02");
var bucket=m.Buckets[index];var before=bucket.position;
Undo.RecordObject(bucket,"Align moving bucket to cable");
var position=(Vector3)at.Invoke(m,new object[]{offsets[index]});
var direction=(Vector3)at.Invoke(m,new object[]{offsets[index]+.25f})-(Vector3)at.Invoke(m,new object[]{offsets[index]-.25f});direction.y=0;
bucket.SetPositionAndRotation(position,Quaternion.LookRotation(direction,Vector3.up));
PrefabUtility.RecordPrefabInstancePropertyModifications(bucket);
UnityEditor.SceneManagement.EditorSceneManager.MarkSceneDirty(s);
UnityEditor.SceneManagement.EditorSceneManager.SaveScene(s);
Selection.activeGameObject=m.gameObject;
var e=Editor.CreateEditor(m,typeof(CablewayMovementManagerEditor));
var poses=m.Buckets.Select(t=>EditorJsonUtility.ToJson(t)).ToArray();
e.GetType().GetMethod("StartPreview",flags).Invoke(e,null);
var view=SceneView.lastActiveSceneView;
if(view!=null)view.LookAt(m.Buckets[0].position+Vector3.down,Quaternion.Euler(12,135,0),13f,false,true);
var report=new {editorID=e.GetInstanceID(),began=EditorApplication.timeSinceStartup,poses,firstPosition=new[]{m.Buckets[0].position.x,m.Buckets[0].position.y,m.Buckets[0].position.z},alignedBucket=bucket.name,alignmentMeters=Vector3.Distance(before,position)};
System.IO.File.WriteAllText("ArtSource/Cableway/Movement/live_preview_start.json",Newtonsoft.Json.JsonConvert.SerializeObject(report,Newtonsoft.Json.Formatting.Indented));
return new {started=AnimationMode.InAnimationMode(),editorID=e.GetInstanceID(),alignmentMeters=Vector3.Distance(before,position),playMode=EditorApplication.isPlaying};
