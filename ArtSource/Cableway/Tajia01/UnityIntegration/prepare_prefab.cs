var dir = "Assets/Art Resources/Environment/Cableway/Tajia01_Rebuilt";
var scene = UnityEngine.SceneManagement.SceneManager.GetSceneByPath("Assets/Scenes/Main Game Scene.unity");
var old = scene.GetRootGameObjects().SelectMany(r => r.GetComponentsInChildren<UnityEngine.Transform>(true)).Single(t => t.name == "tajia01");
var oldMesh = old.GetComponent<UnityEngine.MeshFilter>().sharedMesh;
var oldBounds = oldMesh.bounds;
var foot = oldMesh.vertices.Where(v => v.y < oldBounds.min.y + oldBounds.size.y * .1f).ToArray();
var baseCenter = new UnityEngine.Vector3((foot.Min(v => v.x) + foot.Max(v => v.x)) * .5f, oldBounds.min.y, (foot.Min(v => v.z) + foot.Max(v => v.z)) * .5f);
var towerAsset = UnityEditor.AssetDatabase.LoadAssetAtPath<UnityEngine.GameObject>(dir + "/Tajia01_Tower_v01.fbx");
var bucketAsset = UnityEditor.AssetDatabase.LoadAssetAtPath<UnityEngine.GameObject>(dir + "/Tajia01_CoalBucket_v01.fbx");
var ratio = oldBounds.size.y / towerAsset.GetComponent<UnityEngine.MeshFilter>().sharedMesh.bounds.size.y;
var assembly = new UnityEngine.GameObject("tajia01");
UnityEngine.SceneManagement.SceneManager.MoveGameObjectToScene(assembly, scene);
var tower = (UnityEngine.GameObject)UnityEditor.PrefabUtility.InstantiatePrefab(towerAsset, assembly.transform);
tower.name = "Tower";
tower.transform.localPosition = baseCenter;
tower.transform.localRotation = UnityEngine.Quaternion.identity;
tower.transform.localScale = UnityEngine.Vector3.one * ratio;
var bucket = (UnityEngine.GameObject)UnityEditor.PrefabUtility.InstantiatePrefab(bucketAsset, assembly.transform);
bucket.name = "CoalBucket";
bucket.transform.localPosition = baseCenter + new UnityEngine.Vector3(.3030352f, .952f, 0f) * ratio;
bucket.transform.localRotation = UnityEngine.Quaternion.Euler(0f, 90f, 0f);
bucket.transform.localScale = UnityEngine.Vector3.one * ratio;
var prefab = UnityEditor.PrefabUtility.SaveAsPrefabAsset(assembly, dir + "/Tajia01_Rebuilt.prefab");
UnityEngine.Object.DestroyImmediate(assembly);
var info = new { ratio, baseCenter = baseCenter.ToString("F9"), oldWorldHeight = old.GetComponent<UnityEngine.Renderer>().bounds.size.y, oldLocalPosition = old.localPosition.ToString("F9"), oldLocalRotation = old.localRotation.ToString("F9"), oldLocalScale = old.localScale.ToString("F9"), oldId = UnityEditor.GlobalObjectId.GetGlobalObjectIdSlow(old.gameObject).ToString(), prefab = UnityEditor.AssetDatabase.GetAssetPath(prefab) };
var json = Newtonsoft.Json.JsonConvert.SerializeObject(info, Newtonsoft.Json.Formatting.Indented);
System.IO.File.WriteAllText("ArtSource/Cableway/Tajia01/UnityIntegration/placement_before.json", json);
var sv = UnityEditor.SceneView.lastActiveSceneView;
sv.LookAtDirect(old.GetComponent<UnityEngine.Renderer>().bounds.center, old.rotation * UnityEngine.Quaternion.Euler(12f, 155f, 0f), 23f);
sv.Repaint();
return json;
