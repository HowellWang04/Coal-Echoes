var scene = UnityEngine.SceneManagement.SceneManager.GetSceneByPath("Assets/Scenes/Main Game Scene.unity");
var all = scene.GetRootGameObjects().SelectMany(g => g.GetComponentsInChildren<Transform>(true)).ToArray();
var top = all.Single(t => t.name == "CablewayTower_11");
var previous = all.Single(t => t.name == "CablewayTower_10");
var source = all.Single(t => t.name == "CablewayFoothillStation");
var terminal = source.Find("CablewayReturnTerminal");
var forward = Vector3.ProjectOnPlane(top.position - previous.position, Vector3.up).normalized;
var right = Vector3.Cross(Vector3.up, forward);
var origin = top.position - forward * 4;
var rotation = Quaternion.LookRotation(forward);
var delta = rotation * Quaternion.Inverse(terminal.rotation);
var terrain = Terrain.activeTerrains.Single(t => AssetDatabase.GetAssetPath(t.terrainData) == "Assets/TerrainData/SheepRangeGenerated/Tile_0_0_Main.asset");
float Ground(Vector3 p) => terrain.SampleHeight(p) + terrain.transform.position.y;
float[] V(Vector3 p) => new[] { p.x, p.y, p.z };
var bounds = new Bounds(Vector3.zero, Vector3.zero);
foreach(var mf in source.GetComponentsInChildren<MeshFilter>()) foreach(var vertex in mf.sharedMesh.vertices) bounds.Encapsulate(terminal.InverseTransformPoint(mf.transform.TransformPoint(vertex)));
var samples = new List<float>();
for (float x=bounds.min.x-.5f; x<=bounds.max.x+.5f; x+=.5f) for(float z=bounds.min.z-.5f; z<=bounds.max.z+.5f; z+=.5f) samples.Add(Ground(origin + right*x + forward*z));
var height = samples.Max()+.15f;
origin.y=height;
var rows = source.Cast<Transform>().Select(t=>new {name=t.name, relativePosition=V(terminal.InverseTransformPoint(t.position)), target=V(origin+delta*(t.position-terminal.position)), rotation=V((delta*t.rotation).eulerAngles)}).ToArray();
var report=new { origin=V(origin), forward=V(forward), right=V(right), yaw=rotation.eulerAngles.y, boundsMin=V(bounds.min), boundsMax=V(bounds.max), groundMin=samples.Min(), groundMax=samples.Max(), parts=rows };
System.IO.File.WriteAllText("ArtSource/Cableway/SummitStation/site_plan.json",Newtonsoft.Json.JsonConvert.SerializeObject(report,Newtonsoft.Json.Formatting.Indented));
return report;
